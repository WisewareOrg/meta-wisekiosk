#!/usr/bin/env python3
"""Generate the checksummed Go module closure oapi-codegen needs at build time.

    go-mods.py -- write wisekiosk-backend-go-mods.inc (gitignored, build input)

Clones the pinned WiseKiosk commit and runs `go list -deps` against the
codegen tool's own import path to populate a scratch GOMODCACHE with exactly
the modules it needs, then renders one SRC_URI pair per file the proxy
served. See meta-wisekiosk/recipes-wisekiosk/wisekiosk/README.md.

`render_inc` is the importable seam tests/prechecks/go-mods-test.py drives directly, on
a fabricated cache -- no clone, no network, no real `go`. `fetch_cache` is the
only function that touches either.
"""
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
ROOT = TOOLS.parent

# The pin and the git URL: one file, shared with wisekiosk-frontend_git.bb and wisekiosk-backend_git.bb.
SRC_INC = ROOT / "meta-wisekiosk/recipes-wisekiosk/wisekiosk/wisekiosk-src.inc"

# Written at build entry (Justfile, right after tools/write-build-rev.sh); gitignored.
INC_PATH = ROOT / "meta-wisekiosk/recipes-wisekiosk/wisekiosk/wisekiosk-backend-go-mods.inc"

# The one binary the module closure builds; `go list -deps` on this import path surfaces every module it needs.
CODEGEN_TOOL = "github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen"

# Forced regardless of host Go environment. -modcacherw lets the scratch GOMODCACHE be removed; GOWORK=off ignores a host go.work; GOTOOLCHAIN=local runs the binary _app_go chose.
GO_ENV = {
    "GOPROXY": "https://proxy.golang.org",
    "GOSUMDB": "sum.golang.org",
    "GOFLAGS": "-modcacherw",
    "GOENV": "off",
    "GOWORK": "off",
    "GOTOOLCHAIN": "local",
    "GOOS": "linux",
    "GOARCH": "amd64",
    "GOPRIVATE": "",
    "GONOPROXY": "",
    "GONOSUMDB": "",
}

HEADER = "# Generated by tools/go-mods.py from WiseKiosk {srcrev}; do not edit, do not commit."

# git's own list of repo-local vars (GIT_DIR, GIT_INDEX_FILE, ...), stripped from child git calls.
GIT_LOCAL_VARS = frozenset(subprocess.run(
    ["git", "rev-parse", "--local-env-vars"],
    capture_output=True, text=True, check=True).stdout.split())


def clean_env(**extra):
    env = {k: v for k, v in os.environ.items() if k not in GIT_LOCAL_VARS}
    env.update(extra)
    return env


# Workdirs fetch_cache() has created and not yet removed.
_LEFTOVER_WORKDIRS = []


def _cleanup_workdirs():
    while _LEFTOVER_WORKDIRS:
        shutil.rmtree(_LEFTOVER_WORKDIRS.pop(), ignore_errors=True)


def refuse(message: str) -> int:
    print(f"{message} -- refusing to report a pass", file=sys.stderr)
    return 2


def _src_inc_fields():
    """(url, srcrev) as bitbake reads them from wisekiosk-src.inc."""
    text = SRC_INC.read_text()
    srcrev = re.search(r'^SRCREV\s*=\s*"([0-9a-f]{40})"', text, re.M).group(1)
    src_uri = re.search(r'^SRC_URI\s*=\s*"([^"]+)"', text, re.M).group(1)
    scheme_and_path, *params = src_uri.split(";")
    protocol = next((p.split("=", 1)[1] for p in params
                      if p.startswith("protocol=")), None)
    _, _, rest = scheme_and_path.partition("://")
    return f"{protocol or 'https'}://{rest}", srcrev


def _escape_module_path(path: str) -> str:
    """Go's own on-disk module-cache escaping: each ASCII uppercase letter
    becomes "!" plus its lower-case form. Applied to `go list -json`'s
    unescaped Module.Path."""
    return "".join(f"!{c.lower()}" if "A" <= c <= "Z" else c for c in path)


def _escaped_modules(cache_dir: Path):
    """(escaped, version, ext, file) for every zip/mod file `go mod download`
    left under cache_dir; `escaped` is read off the directory names as-is."""
    download = Path(cache_dir) / "cache" / "download"
    if not download.is_dir():
        return
    for at_v in download.rglob("@v"):
        if not at_v.is_dir():
            continue
        escaped = at_v.parent.relative_to(download).as_posix()
        for f in at_v.iterdir():
            if f.suffix in (".zip", ".mod"):
                yield escaped, f.stem, f.suffix[1:], f


def render_inc(cache_dir: Path, srcrev: str) -> str:
    order = {"zip": 0, "mod": 1}
    entries = sorted(_escaped_modules(cache_dir),
                     key=lambda e: (e[0], e[1], order[e[2]]))

    lines = [HEADER.format(srcrev=srcrev), "",
             f'WISEKIOSK_GOMODS_SRCREV = "{srcrev}"', ""]
    for escaped, version, ext, path in entries:
        digest = hashlib.sha256(f"{escaped}@{version}.{ext}".encode()).hexdigest()
        ident = f"gomod_{digest[:16]}"
        sha256hex = hashlib.sha256(path.read_bytes()).hexdigest()
        url = f"https://proxy.golang.org/{escaped}/@v/{version}.{ext}"
        downloadfilename = f"gomod/{escaped}/@v/{version}.{ext}"
        subdir = f"goproxy/{escaped}/@v"
        lines.append(
            f'SRC_URI += "{url};downloadfilename={downloadfilename};'
            f'subdir={subdir};unpack=0;name={ident}"')
        lines.append(f'SRC_URI[{ident}.sha256sum] = "{sha256hex}"')
    return "\n".join(lines) + "\n"


def _app_go(repo: Path) -> str:
    """The `go` binary backend/go.mod calls for. GOTOOLCHAIN=auto lets Go
    download it into the host's own GOMODCACHE, not the scratch one; stderr is
    left uncaptured."""
    goroot = subprocess.run(
        ["go", "env", "GOROOT"], cwd=repo / "backend",
        env=clean_env(**dict(GO_ENV, GOTOOLCHAIN="auto")),
        check=True, stdout=subprocess.PIPE, text=True).stdout.strip()
    return str(Path(goroot) / "bin" / "go")


def current_srcrev(inc_path: Path = INC_PATH):
    """The WISEKIOSK_GOMODS_SRCREV inc_path already records, or None if the
    file is missing or carries none."""
    if not Path(inc_path).exists():
        return None
    m = re.search(r'^WISEKIOSK_GOMODS_SRCREV\s*=\s*"([0-9a-f]{40})"',
                  Path(inc_path).read_text(), re.M)
    return m.group(1) if m else None


def _deps_modules(list_json: str):
    """(path, version) for every non-main module that `go list -json=Dir,Module
    -deps` reports as providing at least one package, deduplicated, in
    first-seen order. The output is a stream of concatenated JSON objects, so
    this decodes one object at a time."""
    decoder = json.JSONDecoder()
    seen, modules = set(), []
    pos, length = 0, len(list_json)
    while pos < length:
        while pos < length and list_json[pos].isspace():
            pos += 1
        if pos >= length:
            break
        obj, pos = decoder.raw_decode(list_json, pos)
        module = obj.get("Module")
        if not module or module.get("Main"):
            continue
        key = (module["Path"], module["Version"])
        if key not in seen:
            seen.add(key)
            modules.append(key)
    return modules


def check_complete(modules, cache_dir: Path):
    """Every (path, version) in `modules` must have its escaped `.zip` under
    cache_dir. Returns the pairs missing their .zip; empty means complete. A
    module absent from `modules` may keep a mod-only entry."""
    have_zip = {(escaped, version) for escaped, version, ext, _
                in _escaped_modules(cache_dir) if ext == "zip"}
    return [(path, version) for path, version in modules
            if (_escape_module_path(path), version) not in have_zip]


def _deps_include_codegen_tool(modules) -> bool:
    """True if some module in `modules` is the one providing CODEGEN_TOOL: a
    prefix of it ending at a `/` boundary, or equal to it."""
    return any(CODEGEN_TOOL == path or CODEGEN_TOOL.startswith(path + "/")
               for path, _ in modules)


def fetch_cache(url: str, srcrev: str) -> Path:
    """Clone the pinned commit and run the one Go command that touches the
    network: `go list -deps` against oapi-codegen's own import path, which
    downloads exactly the modules it needs into a scratch GOMODCACHE."""
    workdir = Path(tempfile.mkdtemp(prefix="go-mods-"))
    _LEFTOVER_WORKDIRS.append(workdir)
    repo = workdir / "repo"
    subprocess.run(["git", "clone", "--quiet", url, str(repo)], check=True,
                   env=clean_env())
    subprocess.run(["git", "-C", str(repo), "checkout", "--quiet", srcrev],
                   check=True, env=clean_env())

    go = _app_go(repo)

    gomodcache = workdir / "gomodcache"
    gomodcache.mkdir()
    # GOCACHE is isolated too: a warm host build cache can skip extracting a module's .zip into the scratch GOMODCACHE.
    gocache = workdir / "gocache"
    gocache.mkdir()
    env = clean_env(**GO_ENV, GOMODCACHE=str(gomodcache), GOCACHE=str(gocache))
    result = subprocess.run(
        [go, "list", "-json=Dir,Module", "-deps", CODEGEN_TOOL],
        cwd=repo / "backend", env=env, check=True,
        capture_output=True, text=True)

    modules = _deps_modules(result.stdout)
    if not _deps_include_codegen_tool(modules):
        sys.exit(refuse(
            f"go list -deps reported no module providing {CODEGEN_TOOL} -- "
            "its own module must always appear, so this output cannot be "
            "trusted"))
    missing = check_complete(modules, gomodcache)
    if missing:
        named = ", ".join(f"{p}@{v}" for p, v in missing)
        sys.exit(refuse(
            "go list -deps reported modules whose .zip never reached the "
            f"cache: {named}"))
    return gomodcache


def main() -> int:
    if sys.argv[1:]:
        print(__doc__.strip().split("\n\n")[1], file=sys.stderr)
        return 2

    url, srcrev = _src_inc_fields()
    if current_srcrev(INC_PATH) == srcrev:
        return 0

    try:
        cache_dir = fetch_cache(url, srcrev)
        rendered = render_inc(cache_dir, srcrev)
    finally:
        _cleanup_workdirs()

    INC_PATH.parent.mkdir(parents=True, exist_ok=True)
    tmp = INC_PATH.with_suffix(INC_PATH.suffix + ".tmp")
    tmp.write_text(rendered)
    try:
        os.replace(tmp, INC_PATH)
    except OSError:
        tmp.unlink(missing_ok=True)
        raise
    return 0


if __name__ == "__main__":
    sys.exit(main())
