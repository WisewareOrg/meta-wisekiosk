#!/usr/bin/env python3
"""Self-test for tools/go-mods.py's rendering seam. Run by CI.

    go-mods-test.py             -- every case

`render_inc(cache_dir, srcrev)` walks a GOMODCACHE laid out as `go mod download`
leaves one (`cache/download/<escaped module path>/@v/<version>.{zip,mod,...}`)
and renders the recipe include. Every fixture is such a cache; no case runs a
real `go list` or clone. Fixtures use Go's on-disk escaping directly (an
uppercase letter becomes `!` + its lower-case form).
"""
import contextlib
import hashlib
import importlib.util
import io
import json
import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path
from types import SimpleNamespace

TOOLS = Path(__file__).resolve().parents[2] / "tools"
sys.dont_write_bytecode = True


def load(name):
    spec = importlib.util.spec_from_file_location(
        name.replace("-", "_"), TOOLS / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


go_mods = load("go-mods")

PASS, FAIL = [], []


def case(name, got, want):
    (PASS if got == want else FAIL).append(name)
    if got != want:
        print(f"FAIL  {name}\n        want {want!r}\n        got  {got!r}")


SRCREV = "1becdf0dd12943bc7f98d6d52a76494bef02fb1f"


def seed(gomodcache, escaped, version, ext, content):
    """One file at the exact path `go mod download` would leave it."""
    p = Path(gomodcache) / "cache" / "download" / escaped / "@v" / f"{version}.{ext}"
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(content)
    return p


def entry_id(escaped, version, ext):
    digest = hashlib.sha256(f"{escaped}@{version}.{ext}".encode()).hexdigest()
    return f"gomod_{digest[:16]}"


def entry_lines(escaped, version, ext, sha256hex):
    """The exact two-line SRC_URI pair the plan specifies for one file."""
    ident = entry_id(escaped, version, ext)
    url = f"https://proxy.golang.org/{escaped}/@v/{version}.{ext}"
    downloadfilename = f"gomod/{escaped}/@v/{version}.{ext}"
    subdir = f"goproxy/{escaped}/@v"
    return [
        f'SRC_URI += "{url};downloadfilename={downloadfilename};'
        f'subdir={subdir};unpack=0;name={ident}"',
        f'SRC_URI[{ident}.sha256sum] = "{sha256hex}"',
    ]


def src_uri_lines(rendered):
    """Only the SRC_URI body lines, in order."""
    return [ln for ln in rendered.splitlines() if ln.startswith("SRC_URI")]


def header_cases():
    with tempfile.TemporaryDirectory() as tmp:
        seed(tmp, "example.com/a", "v1.0.0", "zip", b"zip-bytes")
        seed(tmp, "example.com/a", "v1.0.0", "mod", b"mod-bytes")
        rendered = go_mods.render_inc(Path(tmp), SRCREV)
    case("render_inc: first line is the exact generated-by header",
         rendered.splitlines()[0],
         f"# Generated by tools/go-mods.py from WiseKiosk {SRCREV}; "
         "do not edit, do not commit.")
    case("render_inc: names the srcrev it was rendered from",
         rendered.splitlines()[2],
         f'WISEKIOSK_GOMODS_SRCREV = "{SRCREV}"')


def entry_shape_cases():
    """One module, one version, both files: the exact SRC_URI entry form,
    the id derivation, and that sha256 is taken over the real fixture bytes."""
    zip_bytes = b"a fixture zip payload, not a real Go module"
    mod_bytes = b"module example.com/a\n\ngo 1.24\n"
    with tempfile.TemporaryDirectory() as tmp:
        seed(tmp, "example.com/a", "v1.0.0", "zip", zip_bytes)
        seed(tmp, "example.com/a", "v1.0.0", "mod", mod_bytes)
        lines = src_uri_lines(go_mods.render_inc(Path(tmp), SRCREV))

    want = (
        entry_lines("example.com/a", "v1.0.0", "zip",
                    hashlib.sha256(zip_bytes).hexdigest())
        + entry_lines("example.com/a", "v1.0.0", "mod",
                      hashlib.sha256(mod_bytes).hexdigest())
    )
    case("render_inc: zip-then-mod, exact SRC_URI entry form and sha256",
         lines, want)


def mod_only_cases():
    """A version with a .mod but no .zip (a module used only for its go.mod,
    e.g. a transitive dependency of the build list) emits the .mod alone."""
    mod_bytes = b"module example.com/modonly\n\ngo 1.24\n"
    with tempfile.TemporaryDirectory() as tmp:
        seed(tmp, "example.com/modonly", "v0.1.0", "mod", mod_bytes)
        lines = src_uri_lines(go_mods.render_inc(Path(tmp), SRCREV))

    case("render_inc: a mod-only version emits exactly one SRC_URI pair",
         len(lines), 2)
    case("render_inc: a mod-only version emits only the .mod entry",
         lines,
         entry_lines("example.com/modonly", "v0.1.0", "mod",
                     hashlib.sha256(mod_bytes).hexdigest()))


def escaping_and_sort_cases():
    """Four modules seeded out of order, one with an uppercase-escaped segment and
    one with two versions; render_inc sorts by escaped path then version and
    keeps the escaped segment verbatim."""
    files = {
        ("example.com/b", "v1.0.0", "zip"): b"b-zip",
        ("example.com/b", "v1.0.0", "mod"): b"b-mod",
        ("example.com/!x", "v1.0.0", "zip"): b"bangx-zip",
        ("example.com/!x", "v1.0.0", "mod"): b"bangx-mod",
        ("example.com/a", "v2.0.0", "mod"): b"a-v2-mod",
        ("example.com/a", "v1.0.0", "zip"): b"a-v1-zip",
        ("example.com/a", "v1.0.0", "mod"): b"a-v1-mod",
    }
    # Seeded in an order that is neither path-sorted nor version-sorted.
    order = [
        ("example.com/b", "v1.0.0", "zip"),
        ("example.com/a", "v2.0.0", "mod"),
        ("example.com/!x", "v1.0.0", "mod"),
        ("example.com/a", "v1.0.0", "zip"),
        ("example.com/!x", "v1.0.0", "zip"),
        ("example.com/a", "v1.0.0", "mod"),
        ("example.com/b", "v1.0.0", "mod"),
    ]
    with tempfile.TemporaryDirectory() as tmp:
        for key in order:
            escaped, version, ext = key
            seed(tmp, escaped, version, ext, files[key])
        lines = src_uri_lines(go_mods.render_inc(Path(tmp), SRCREV))

    want = []
    for escaped, version, ext in (
        ("example.com/!x", "v1.0.0", "zip"),
        ("example.com/!x", "v1.0.0", "mod"),
        ("example.com/a", "v1.0.0", "zip"),
        ("example.com/a", "v1.0.0", "mod"),
        ("example.com/a", "v2.0.0", "mod"),
        ("example.com/b", "v1.0.0", "zip"),
        ("example.com/b", "v1.0.0", "mod"),
    ):
        want += entry_lines(escaped, version, ext,
                             hashlib.sha256(files[(escaped, version, ext)])
                             .hexdigest())

    case("render_inc: sorted by case-escaped path then version, "
         "zip before mod, uppercase escaping preserved verbatim",
         lines, want)


# --- toolchain selection: the app's go.mod picks the `go` that runs go list --
#
# `fetch_cache` asks Go which toolchain backend/go.mod calls for (`go env
# GOROOT` under GOTOOLCHAIN=auto) and runs `go list` with that binary. The cases
# monkeypatch `subprocess.run`.

GO_MOD = "module example.com/fixture\n\ngo 1.27\n"
FAKE_GOROOT = "/fake/gomodcache/golang.org/toolchain@v0.0.1-go1.27.0.linux-amd64"


class FakeToolchain:
    """Stands in for the four subprocess.run calls fetch_cache makes: `git clone`,
    `git checkout`, `go env GOROOT` and `go list`. Any other call is an
    AssertionError.

    `go list`'s fake stdout defaults to naming DEFAULT_MODULE alone, and the
    default seed puts that module's .zip in the fake GOMODCACHE. Tests of the
    codegen-tool-presence or completeness checks pass go_list_stdout or
    seed_gomodcache."""

    DEFAULT_MODULE = ("github.com/oapi-codegen/oapi-codegen/v2", "v2.4.1")

    def __init__(self, go_list_stdout=None, seed_gomodcache=None):
        self.go_list_stdout = (go_list_stdout if go_list_stdout is not None
                               else self._default_deps_stream())
        self.seed_gomodcache = (seed_gomodcache if seed_gomodcache is not None
                                else self._seed_default_module)
        self.goroot_env = None
        self.goroot_cwd = None
        self.go_list_called = False
        self.go_list_binary = None
        self.go_list_env = None
        self.workdir = None

    def _default_deps_stream(self):
        path, version = self.DEFAULT_MODULE
        return json.dumps({"Dir": "/x",
                           "Module": {"Path": path, "Version": version}})

    def _seed_default_module(self, gomodcache):
        path, version = self.DEFAULT_MODULE
        seed(gomodcache, path, version, "zip", b"fixture zip payload")

    def __call__(self, argv, **kwargs):
        if argv[:2] == ["git", "clone"]:
            repo = Path(argv[-1])
            self.workdir = repo.parent
            (repo / "backend").mkdir(parents=True)
            (repo / "backend" / "go.mod").write_text(GO_MOD)
            return SimpleNamespace(returncode=0)
        if argv[:2] == ["git", "-C"] and "checkout" in argv:
            return SimpleNamespace(returncode=0)
        if argv == ["go", "env", "GOROOT"]:
            self.goroot_env = kwargs.get("env")
            self.goroot_cwd = kwargs.get("cwd")
            return SimpleNamespace(stdout=FAKE_GOROOT + "\n", returncode=0)
        if argv[1:2] == ["list"]:
            self.go_list_called = True
            self.go_list_binary = argv[0]
            self.go_list_env = kwargs.get("env")
            # Seeds the cache fetch_cache created, just before `go list` returns.
            if self.seed_gomodcache is not None:
                self.seed_gomodcache(self.workdir / "gomodcache")
            return SimpleNamespace(stdout=self.go_list_stdout, returncode=0)
        raise AssertionError(f"unexpected subprocess call in fetch_cache: {argv}")


def run_fetch_cache(go_list_stdout=None, seed_gomodcache=None):
    """fetch_cache(), every subprocess call faked: returns (the SystemExit code
    fetch_cache raised, or None; its stderr; the FakeToolchain)."""
    toolchain = FakeToolchain(go_list_stdout, seed_gomodcache)
    was_run = subprocess.run
    subprocess.run = toolchain
    stderr = io.StringIO()
    code = None
    try:
        with contextlib.redirect_stderr(stderr):
            try:
                go_mods.fetch_cache("https://example.invalid/repo.git", "f" * 40)
            except SystemExit as exc:
                code = exc.code
    finally:
        subprocess.run = was_run
        if toolchain.workdir is not None:
            shutil.rmtree(toolchain.workdir, ignore_errors=True)
    return code, stderr.getvalue(), toolchain


def toolchain_selection_cases():
    host_gomodcache = "/nonexistent/host/gomodcache"
    was_gomodcache = os.environ.get("GOMODCACHE")
    os.environ["GOMODCACHE"] = host_gomodcache
    try:
        code, err, tc = run_fetch_cache()
    finally:
        if was_gomodcache is None:
            os.environ.pop("GOMODCACHE", None)
        else:
            os.environ["GOMODCACHE"] = was_gomodcache

    case("fetch_cache: proceeds with no host-version gate", code, None)
    case("fetch_cache: the toolchain is resolved inside the app's own module",
         tc.goroot_cwd is not None and tc.workdir is not None
         and Path(tc.goroot_cwd) == tc.workdir / "repo" / "backend", True)
    case("fetch_cache: the resolve may switch toolchains (GOTOOLCHAIN=auto)",
         (tc.goroot_env or {}).get("GOTOOLCHAIN"), "auto")
    # The switch downloads into GOMODCACHE, whose zips render_inc turns into SRC_URI entries.
    case("fetch_cache: the toolchain download lands in the host GOMODCACHE, "
         "not the scratch one", (tc.goroot_env or {}).get("GOMODCACHE"),
         host_gomodcache)
    case("fetch_cache: go list runs the binary the resolve selected",
         tc.go_list_binary, f"{FAKE_GOROOT}/bin/go")
    case("fetch_cache: go list never switches again (GOTOOLCHAIN=local)",
         (tc.go_list_env or {}).get("GOTOOLCHAIN"), "local")


# --- GOCACHE isolation -------------------------------------------------------
#
# GOCACHE is a fresh scratch dir per run, like GOMODCACHE; a warm shared build
# cache lets `go list` skip extracting a module's .zip.

def gocache_isolation_cases():
    host_gocache = "/nonexistent/host/shared/go-build"
    was_gocache = os.environ.get("GOCACHE")
    os.environ["GOCACHE"] = host_gocache
    try:
        code, err, tc = run_fetch_cache()
    finally:
        if was_gocache is None:
            os.environ.pop("GOCACHE", None)
        else:
            os.environ["GOCACHE"] = was_gocache

    gocache = (tc.go_list_env or {}).get("GOCACHE")
    case("fetch_cache: GOCACHE differs from the inherited host GOCACHE",
         gocache != host_gocache and gocache is not None, True)
    # Under the run's own temp root, alongside GOMODCACHE.
    case("fetch_cache: GOCACHE lies under the run's own temp root",
         gocache is not None and tc.workdir is not None
         and Path(gocache).resolve().is_relative_to(tc.workdir.resolve()),
         True)


# --- _deps_modules: the package stream reduced to (path, version) pairs ----
#
# `go list -json=Dir,Module -deps` emits one concatenated, pretty-printed JSON
# object per package. _deps_modules yields one (path, version) per
# package-providing, non-main module, in first-seen order.

def deps_modules_cases():
    def obj(module=None):
        rec = {"Dir": "/x"}
        if module is not None:
            rec["Module"] = module
        return json.dumps(rec, indent=2)

    main_mod = {"Path": "example.com/mainmod", "Version": "", "Main": True}
    a = {"Path": "example.com/a", "Version": "v1.0.0"}
    b = {"Path": "example.com/b", "Version": "v2.0.0"}

    # Objects joined by newlines, as go list emits them.
    stream = "\n".join([obj(main_mod), obj(None), obj(a), obj(a), obj(b)])
    modules = go_mods._deps_modules(stream)

    case("_deps_modules: the main module is excluded",
         all(path != "example.com/mainmod" for path, _ in modules), True)
    case("_deps_modules: a std-library package (no Module field) is skipped",
         len(modules), 2)
    case("_deps_modules: a module repeated across packages is deduplicated",
         modules.count(("example.com/a", "v1.0.0")), 1)
    case("_deps_modules: first-seen order is preserved",
         modules, [("example.com/a", "v1.0.0"), ("example.com/b", "v2.0.0")])


# --- check_complete: every package-providing module needs its .zip ---------
#
# A module named in `modules` provides a package, so its .zip must be cached; a
# module absent from `modules` may keep a mod-only entry.

def check_complete_cases():
    with tempfile.TemporaryDirectory() as tmp:
        # A package-providing module whose cache entry has only a .mod is reported missing.
        seed(tmp, "example.com/nozip", "v1.0.0", "mod",
             b"module example.com/nozip\n")
        missing = go_mods.check_complete(
            [("example.com/nozip", "v1.0.0")], Path(tmp))
        case("check_complete: a package-providing module with only a .mod "
             "is reported missing",
             missing, [("example.com/nozip", "v1.0.0")])

    with tempfile.TemporaryDirectory() as tmp:
        # The same module with its .zip present.
        seed(tmp, "example.com/haszip", "v1.0.0", "mod",
             b"module example.com/haszip\n")
        seed(tmp, "example.com/haszip", "v1.0.0", "zip",
             b"a fixture zip payload")
        missing = go_mods.check_complete(
            [("example.com/haszip", "v1.0.0")], Path(tmp))
        case("check_complete: a package-providing module with its .zip "
             "present is complete", missing, [])

    with tempfile.TemporaryDirectory() as tmp:
        # A mod-only module never named in `modules` is not a failure.
        seed(tmp, "example.com/modonly", "v0.1.0", "mod",
             b"module example.com/modonly\n")
        missing = go_mods.check_complete([], Path(tmp))
        case("check_complete: a mod-only module absent from `modules` is "
             "not reported", missing, [])

    with tempfile.TemporaryDirectory() as tmp:
        # Module.Path is unescaped ("example.com/Foo"); the cache directory is escaped ("example.com/!foo").
        seed(tmp, "example.com/!foo", "v1.0.0", "zip", b"a fixture zip payload")
        missing = go_mods.check_complete(
            [("example.com/Foo", "v1.0.0")], Path(tmp))
        case("check_complete: an uppercase module path is escaped before "
             "the lookup, so its .zip is found",
             missing, [])


# --- check_complete is wired into fetch_cache's own refusal -----------------
#
# These cases drive check_complete through fetch_cache with a real `go list
# -deps` stream and a fixture GOMODCACHE.

def completeness_wiring_cases():
    codegen_path, codegen_version = FakeToolchain.DEFAULT_MODULE
    # Two packages: the codegen tool's own module and a second module under test.
    deps_stream = "\n".join(json.dumps(o) for o in (
        {"Dir": "/x", "Module": {"Path": codegen_path,
                                 "Version": codegen_version}},
        {"Dir": "/y", "Module": {"Path": "example.com/needed",
                                 "Version": "v1.0.0"}}))

    # Seeding only the codegen module leaves "example.com/needed" missing.
    def seed_codegen_only(gomodcache):
        seed(gomodcache, codegen_path, codegen_version, "zip",
             b"fixture zip payload")

    code, err, tc = run_fetch_cache(go_list_stdout=deps_stream,
                                    seed_gomodcache=seed_codegen_only)
    case("fetch_cache: a module missing its .zip is refused", code, 2)
    case("fetch_cache: the refusal names the missing module",
         "example.com/needed@v1.0.0" in err, True)
    case("fetch_cache: the refusal does not also name a module that has "
         "its .zip", f"{codegen_path}@{codegen_version}" in err, False)

    # Both modules' .zip reach the cache; overriding seed_gomodcache replaces the default, so the codegen module is seeded too.
    def seed_both(gomodcache):
        seed(gomodcache, codegen_path, codegen_version, "zip",
             b"fixture zip payload")
        seed(gomodcache, "example.com/needed", "v1.0.0", "zip",
             b"a fixture zip payload")

    code, err, tc = run_fetch_cache(go_list_stdout=deps_stream,
                                    seed_gomodcache=seed_both)
    case("fetch_cache: a module with its .zip present is not refused",
         code, None)


# --- fetch_cache refuses when go list never names its own target -----------
#
# The codegen tool's own module appears in every real `go list -deps` result;
# its absence is refused before completeness is checked.

def codegen_tool_presence_cases():
    # No output at all, set explicitly to override the default.
    code, err, tc = run_fetch_cache(go_list_stdout="")
    case("fetch_cache: empty go list output refuses rather than reporting "
         "an empty closure complete", code, 2)
    case("fetch_cache: the refusal names the codegen tool's import path",
         go_mods.CODEGEN_TOOL in err, True)

    # Non-empty without the codegen tool's module, whose .zip is seeded.
    unrelated = json.dumps({"Dir": "/x",
                            "Module": {"Path": "gopkg.in/yaml.v3",
                                      "Version": "v3.0.1"}})

    def seed_unrelated(gomodcache):
        seed(gomodcache, "gopkg.in/yaml.v3", "v3.0.1", "zip",
             b"fixture zip payload")

    code, err, tc = run_fetch_cache(go_list_stdout=unrelated,
                                    seed_gomodcache=seed_unrelated)
    case("fetch_cache: a deps list missing the codegen tool's module "
         "refuses even when otherwise complete", code, 2)
    case("fetch_cache: that refusal names the codegen tool, not a "
         "completeness complaint", go_mods.CODEGEN_TOOL in err, True)

    # A module path that is a raw string prefix of CODEGEN_TOOL but not a package-path-boundary ancestor; its .zip is seeded.
    near_miss_path = "github.com/oapi-codegen/oapi"
    near_miss_version = "v1.0.0"
    near_miss = json.dumps({"Dir": "/x",
                            "Module": {"Path": near_miss_path,
                                      "Version": near_miss_version}})

    def seed_near_miss(gomodcache):
        seed(gomodcache, near_miss_path, near_miss_version, "zip",
             b"fixture zip payload")

    code, err, tc = run_fetch_cache(go_list_stdout=near_miss,
                                    seed_gomodcache=seed_near_miss)
    case("fetch_cache: a string-prefix, non-boundary module is not "
         "mistaken for the codegen tool's own module", code, 2)
    case("fetch_cache: that refusal names the codegen tool",
         go_mods.CODEGEN_TOOL in err, True)


# --- current_srcrev: the "already current" seam for skip-when-current -----

def current_srcrev_cases():
    with tempfile.TemporaryDirectory() as tmp:
        inc_path = Path(tmp) / "wisekiosk-backend-go-mods.inc"
        inc_path.write_text(
            f'WISEKIOSK_GOMODS_SRCREV = "{SRCREV}"\n')
        case("current_srcrev: reads the srcrev an existing .inc records",
             go_mods.current_srcrev(inc_path), SRCREV)

    with tempfile.TemporaryDirectory() as tmp:
        inc_path = Path(tmp) / "wisekiosk-backend-go-mods.inc"
        inc_path.write_text('SRC_URI += "https://example.invalid/x.zip"\n')
        case("current_srcrev: an .inc carrying no such variable is None",
             go_mods.current_srcrev(inc_path), None)

    case("current_srcrev: a path that does not exist is None",
         go_mods.current_srcrev(Path("/nonexistent/wisekiosk-backend-go-mods.inc")),
         None)


def main() -> int:
    header_cases()
    entry_shape_cases()
    mod_only_cases()
    escaping_and_sort_cases()
    toolchain_selection_cases()
    gocache_isolation_cases()
    deps_modules_cases()
    check_complete_cases()
    completeness_wiring_cases()
    codegen_tool_presence_cases()
    current_srcrev_cases()
    print(f"\npass={len(PASS)} fail={len(FAIL)} skip=0")
    return 1 if FAIL else 0


if __name__ == "__main__":
    sys.exit(main())
